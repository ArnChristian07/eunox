export function formatSampleAmount(currency: Currency): string {
  const decimals = currency.decimals ?? 2;
  const formatted = decimals === 0 ? '1,234' : `1,234.${'56'.padEnd(decimals, '0').slice(0, decimals)}`;
  return `${currency.symbol}${formatted}`;
}
